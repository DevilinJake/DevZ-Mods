"""Writes src/config.cpp from settings.json and durability.csv.

Each row's new barrelArmor is CurrentArmor x its Multiplier from durability.csv, or, if that's
blank, x WeaponMultiplier (weapons) or SuppressorMultiplier (suppressors and other muzzle
attachments) from settings.json. Higher barrelArmor = less wear per shot.

Usage:
    python generate_config.py [-o src/config.cpp]
"""
import argparse, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_WeaponDurability'


def load_settings(path=os.path.join(HERE, 'settings.json')):
    with open(path, encoding='utf-8') as f:
        s = json.load(f)
    return {'Weapon': float(s.get('WeaponMultiplier', 1)), 'Suppressor': float(s.get('SuppressorMultiplier', 1))}


def compute(settings=None, table=os.path.join(HERE, 'durability.csv')):
    settings = settings or load_settings()
    with open(table, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        own = r['Multiplier'].strip()
        mult = float(own) if own else settings['Weapon' if r['Type'] == 'Weapon' else 'Suppressor']
        if mult <= 0:
            raise SystemExit(f"{r['Class']}: multiplier must be above 0 (got {mult})")
        r['old'] = float(r['CurrentArmor'])
        r['mult'] = mult
        r['new'] = round(r['old'] * mult, 4)
    return rows


def ordered(rows):
    """Rows sorted so a class always comes after a parent that's also in the file."""
    by_name = {r['Class'].lower(): r for r in rows}

    def depth(r):
        d, parent, seen = 0, r['Parent'].lower(), set()
        while parent in by_name and parent not in seen:
            seen.add(parent); d += 1
            parent = by_name[parent]['Parent'].lower()
        return d
    return sorted(rows, key=lambda r: (depth(r), r['Type'] != 'Weapon', r['Source'] != 'Vanilla', r['Class'].lower()))


def fmt(x):
    return f'{x:.4f}'.rstrip('0').rstrip('.')


def write_config(rows, out):
    changed = [r for r in rows if r['mult'] != 1]
    addons = ['DZ_Data']
    for r in changed:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    lines = [
        '// Generated by generate_config.py from settings.json and durability.csv. Change those and',
        '// re-run it, or edit the numbers below by hand. barrelArmor: higher = less wear per shot.',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons) + '};',
        '\t};',
        '};',
    ]
    for section in ('CfgWeapons', 'CfgVehicles'):
        part = ordered([r for r in changed if r['Section'] == section])
        if not part:
            continue
        names = {r['Class'].lower() for r in part}
        parents = sorted({r['Parent'] for r in part if r['Parent'].lower() not in names}, key=str.lower)
        lines += ['', f'class {section}', '{']
        lines += [f'\tclass {p};' for p in parents]
        lines.append('')
        for r in part:
            lines.append(f"\tclass {r['Class']}: {r['Parent']} {{ barrelArmor = {fmt(r['new'])}; }};"
                         f"  // {r['Example']}, was {fmt(r['old'])} (x{fmt(r['mult'])})")
        lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()
    changed = write_config(compute(), args.output)
    print(f'{len(changed)} weapons and attachments changed, written to {args.output}')


if __name__ == '__main__':
    main()
