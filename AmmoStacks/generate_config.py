"""Writes src/config.cpp from settings.json and ammo.csv.

Each ammo type's new stack is:
  - its NewStack in ammo.csv, if filled in
  - otherwise CurrentStack x Multiplier (rounded), from settings.json
  - single-round items (rockets, 40mm, darts) stay at 1 while LeaveSingleRoundAlone is true

Usage:
    python generate_config.py [-o src/config.cpp]
"""
import argparse, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_AmmoStacks'


def load_settings(path=os.path.join(HERE, 'settings.json')):
    with open(path, encoding='utf-8') as f:
        s = json.load(f)
    return {'Multiplier': float(s.get('Multiplier', 1)),
            'LeaveSingleRoundAlone': bool(s.get('LeaveSingleRoundAlone', True)),
            'MaxStack': int(s.get('MaxStack', 1000))}


def compute_stacks(settings=None, table=os.path.join(HERE, 'ammo.csv')):
    """Rows of ammo.csv with 'old' and 'new' stack sizes added."""
    settings = settings or load_settings()
    with open(table, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        old = int(r['CurrentStack'])
        override = r['NewStack'].strip()
        if override:
            new = int(override)
        elif old == 1 and settings['LeaveSingleRoundAlone']:
            new = 1
        else:
            new = max(1, round(old * settings['Multiplier']))
        if new < 1:
            raise SystemExit(f"{r['Class']}: stack must be 1 or more (got {new})")
        if new > settings['MaxStack']:
            print(f"Warning: {r['Class']} stack {new} is above MaxStack, using {settings['MaxStack']}")
            new = settings['MaxStack']
        r['old'], r['new'] = old, new
    return rows


def write_config(rows, out):
    changed = [r for r in rows if r['new'] != r['old']]
    addons = ['DZ_Data', 'DZ_Weapons_Ammunition']
    for r in changed:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    names = {r['Class'].lower() for r in changed}
    # A changed class whose parent is also changed must come after it
    changed.sort(key=lambda r: (r['Parent'].lower() in names, r['Source'] != 'Vanilla', r['Class'].lower()))
    parents = sorted({r['Parent'] for r in changed if r['Parent'].lower() not in names}, key=str.lower)

    lines = [
        '// Generated by generate_config.py from settings.json and ammo.csv. Change those and',
        '// re-run it, or edit the numbers below by hand: count = rounds per stack;',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons) + '};',
        '\t};',
        '};',
        '',
        'class CfgMagazines',
        '{',
    ]
    lines += [f'\tclass {p};' for p in parents]
    lines.append('')
    for r in changed:
        lines.append(f"\tclass {r['Class']}: {r['Parent']} {{ count = {r['new']}; }};"
                     f"  // {r['Example']}, was {r['old']}")
    lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()

    changed = write_config(compute_stacks(), args.output)
    print(f'{len(changed)} ammo stacks changed, written to {args.output}')


if __name__ == '__main__':
    main()
