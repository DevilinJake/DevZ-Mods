"""Writes src/config.cpp from items.csv.

Every row with Combine = Yes goes into the list the mod's script reads. Those items can be
combined but never split.

Usage:
    python generate_config.py [items.csv] [-o src/config.cpp]
"""
import argparse, csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_CombineNoSplit'


def read_items(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        rows = [r for r in csv.DictReader(f) if r['Combine'].strip().lower() in ('yes', 'y', '1', 'x')]
    for r in rows:
        if not r['Class'].strip() or any(c in r['Class'] for c in '" ,;'):
            raise SystemExit(f"Bad class name in items.csv: {r['Class']!r}")
    return rows


def write_config(rows, out):
    lines = [
        '// Generated by generate_config.py from items.csv. Edit items.csv and re-run it,',
        '// or edit the list below by hand: one class name per line.',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {"DZ_Data", "DZ_Scripts"};',
        '\t};',
        '};',
        '',
        'class CfgMods',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        f'\t\tdir = "{PATCH}";',
        '\t\tname = "DevZ Combine No Split";',
        '\t\tauthor = "DevilinJake";',
        '\t\ttype = "mod";',
        '\t\tdependencies[] = {"World"};',
        '',
        '\t\tclass defs',
        '\t\t{',
        '\t\t\tclass worldScriptModule',
        '\t\t\t{',
        '\t\t\t\tvalue = "";',
        f'\t\t\t\tfiles[] = {{"{PATCH}/scripts/4_World"}};',
        '\t\t\t};',
        '\t\t};',
        '\t};',
        '};',
        '',
        '// Items that can be combined but never split',
        f'class Cfg{PATCH}',
        '{',
        '\titems[] =',
        '\t{',
    ]
    entries = [f'\t\t"{r["Class"].strip()}"' for r in rows]
    for i, r in enumerate(rows):
        comma = ',' if i < len(rows) - 1 else ''
        lines.append(f'{entries[i]}{comma}  // {r["Example"]} ({r["Source"]})')
    lines += ['\t};', '};']

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('items', nargs='?', default=os.path.join(HERE, 'items.csv'))
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()

    rows = read_items(args.items)
    write_config(rows, args.output)
    print(f'{len(rows)} items set to combine without splitting, written to {args.output}')


if __name__ == '__main__':
    main()
