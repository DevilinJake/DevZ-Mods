"""Writes src/config.cpp from settings.json and batteries.csv.

Each row's new energyStorageMax is CurrentCapacity x its Multiplier from batteries.csv, or, if
that's blank, x BatteryMultiplier (batteries) or GasMultiplier (gas canisters) from
settings.json. energyAtSpawn is scaled by the same multiplier, so new batteries spawn as full
as before. Higher energyStorageMax = every device on that battery runs longer.

Usage:
    python generate_config.py [-o src/config.cpp]
"""
import argparse, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_BatteryLife'


def load_settings(path=os.path.join(HERE, 'settings.json')):
    with open(path, encoding='utf-8') as f:
        s = json.load(f)
    return {'Battery': float(s.get('BatteryMultiplier', 1)), 'Gas': float(s.get('GasMultiplier', 1))}


def compute(settings=None, table=os.path.join(HERE, 'batteries.csv')):
    settings = settings or load_settings()
    with open(table, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        own = r['Multiplier'].strip()
        mult = float(own) if own else settings['Battery' if r['Type'] == 'Battery' else 'Gas']
        if mult <= 0:
            raise SystemExit(f"{r['Class']}: multiplier must be above 0 (got {mult})")
        r['old'] = float(r['CurrentCapacity'])
        r['old_spawn'] = float(r['CurrentAtSpawn'])
        r['mult'] = mult
        r['new'] = round(r['old'] * mult, 4)
        r['new_spawn'] = round(r['old_spawn'] * mult, 4)
    return rows


def fmt(x):
    return f'{x:.4f}'.rstrip('0').rstrip('.')


def write_config(rows, out):
    changed = [r for r in rows if r['mult'] != 1]
    addons = ['DZ_Data']
    for r in changed:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    lines = [
        '// Generated by generate_config.py from settings.json and batteries.csv. Change those and',
        '// re-run it, or edit the numbers below by hand. energyStorageMax: higher = lasts longer.',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons) + '};',
        '\t};',
        '};',
    ]
    if changed:
        part = sorted(changed, key=lambda r: (r['Type'] != 'Battery', r['Source'] != 'Vanilla', r['Class'].lower()))
        names = {r['Class'].lower() for r in part}
        parents = sorted({r['Parent'] for r in part if r['Parent'].lower() not in names}, key=str.lower)
        lines += ['', 'class CfgVehicles', '{']
        lines += [f'\tclass {p};' for p in parents]
        lines.append('')
        for r in part:
            spawn = f" energyAtSpawn = {fmt(r['new_spawn'])};" if r['old_spawn'] else ''
            lines.append(f"\tclass {r['Class']}: {r['Parent']} {{ class EnergyManager {{ "
                         f"energyStorageMax = {fmt(r['new'])};{spawn} }}; }};"
                         f"  // {r['Example']}, was {fmt(r['old'])} (x{fmt(r['mult'])})")
        lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()
    changed = write_config(compute(), args.output)
    print(f'{len(changed)} batteries and gas canisters changed, written to {args.output}')


if __name__ == '__main__':
    main()
