"""Writes src/config.cpp from sizes.csv.

Only rows with a NewWidth and NewHeight that differ from the current size go into the config.
Every item that inherits its grid from a changed class changes with it.

Usage:
    python generate_config.py [sizes.csv] [-o src/config.cpp]
"""
import argparse, csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'Nasdara_InventorySizes'


def read_rows(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    changed = []
    for r in rows:
        new_w, new_h = r['NewWidth'].strip(), r['NewHeight'].strip()
        if not new_w and not new_h:
            continue
        w = int(new_w or r['CurrentWidth'] or 0)
        h = int(new_h or r['CurrentHeight'] or 0)
        if w < 1 or h < 1:
            raise SystemExit(f"{r['Class']}: sizes must be 1 or more (got {w}x{h})")
        if w > 10:
            print(f"Warning: {r['Class']} is {w} wide; the inventory panel shows 10 columns")
        if (w, h) != (int(r['CurrentWidth'] or 0), int(r['CurrentHeight'] or 0)):
            changed.append({**r, 'w': w, 'h': h})
    return changed


def write_config(changed, out):
    addons = ['DZ_Data', 'DZ_Characters']
    for r in changed:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    names = {r['Class'].lower() for r in changed}
    # A changed class whose parent is also changed must come after it
    changed.sort(key=lambda r: (r['Parent'].lower() in names, r['Category'], r['Class']))
    parents = sorted({r['Parent'] for r in changed if r['Parent'].lower() not in names}, key=str.lower)

    lines = [
        '// Generated by generate_config.py from sizes.csv. Edit sizes.csv and re-run it,',
        '// or edit the numbers below by hand: itemsCargoSize[] = {width, height};',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons) + '};',
        '\t};',
        '};',
        '',
        'class CfgVehicles',
        '{',
    ]
    lines += [f'\tclass {p};' for p in parents]
    lines.append('')
    category = None
    for r in changed:
        if r['Category'] != category:
            category = r['Category']
            lines.append(f'\t// {category}')
        was = f"was {r['CurrentWidth']}x{r['CurrentHeight']}" if r['CurrentWidth'] else 'had no grid'
        lines.append(f"\tclass {r['Class']}: {r['Parent']} {{ itemsCargoSize[] = {{{r['w']}, {r['h']}}}; }};"
                     f"  // {r['Example']}, {was}")
    lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('sizes', nargs='?', default=os.path.join(HERE, 'sizes.csv'))
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()

    changed = read_rows(args.sizes)
    write_config(changed, args.output)
    print(f'{len(changed)} cargo grids changed, written to {args.output}')


if __name__ == '__main__':
    main()
