"""Writes src/config.cpp from ammo.csv and armour.csv.

ammo.csv: each bullet's new Health and Shock damage is its current value x the multiplier in the
Health / Shock column (blank = unchanged). Every gun that fires that bullet changes with it; to
change one gun only, use the Weapons list in the server's settings file instead (see README).

armour.csv: what share of a bullet's Health, Blood and Shock damage gets through each vest
(0.35 = 35%). Blank = unchanged. Child classes (colour variants) follow their parent.

Usage:
    python generate_config.py [-o src/config.cpp]
"""
import argparse, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_GunDamage'
ZONES = ('Health', 'Blood', 'Shock')


def fmt(x):
    return f'{float(x):.4f}'.rstrip('0').rstrip('.')


def read(name):
    with open(os.path.join(HERE, name), newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def multiplier(row, col):
    value = row.get(col, '').strip()
    m = float(value) if value else 1.0
    if m < 0:
        raise SystemExit(f"{row['Class']}: {col} multiplier can't be below 0 (got {m})")
    return m


def changed_ammo():
    out = []
    for r in read('ammo.csv'):
        # A bullet from another mod would make this mod need that mod to load at all. Those go in the server's
        # Config.json Ammo list instead (HealthMultiplier, ShockMultiplier), which does nothing without the mod.
        if not r['RequiredAddon'].startswith('DZ_') and (r.get('Health', '').strip() or r.get('Shock', '').strip()):
            print(f"Skipped {r['Class']}: it needs {r['RequiredAddon']}. Put it in Config.json's Ammo list instead "
                  f"(HealthMultiplier {r.get('Health') or 1}, ShockMultiplier {r.get('Shock') or 1}).")
            continue
        old = {z: float(r['Current' + z]) for z in ZONES}
        new = {'Health': round(old['Health'] * multiplier(r, 'Health'), 4), 'Blood': old['Blood'],
               'Shock': round(old['Shock'] * multiplier(r, 'Shock'), 4)}
        if new != old:
            out.append((r, old, new))
    return out


def changed_armour():
    out = []
    for r in read('armour.csv'):
        old = {z: float(r['Current' + z]) for z in ZONES}
        new = {z: float(r[z]) if r[z].strip() else old[z] for z in ZONES}
        if any(not 0 <= v <= 1 for v in new.values()):
            raise SystemExit(f"{r['Class']}: armour values go from 0 (blocks all) to 1 (blocks nothing)")
        if new != old:
            out.append((r, old, new))
    return out


def parents_block(rows):
    names = {r['Class'].lower() for r, _, _ in rows}
    return [f'\tclass {p};' for p in sorted({r['Parent'] for r, _, _ in rows if r['Parent'].lower() not in names}, key=str.lower)]


def write_config(ammo, armour, out):
    addons = ['DZ_Data']
    for r, _, _ in ammo + armour:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    lines = [
        '// Generated by generate_config.py from ammo.csv and armour.csv. Change those and re-run',
        '// it. A player has 100 Health, 5000 Blood and 100 Shock (knocked out at 25 Shock or less).',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons + ['DZ_Scripts']) + '};',
        '\t};',
        '};',
        '',
        'class CfgMods',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        f'\t\tdir = "{PATCH}";',
        '\t\tname = "DevZ Gun Damage";',
        '\t\tauthor = "DevilinJake";',
        '\t\ttype = "mod";',
        '\t\tdependencies[] = {"Game", "World", "Mission"};',
        '',
        '\t\tclass defs',
        '\t\t{',
        '\t\t\tclass gameScriptModule',
        '\t\t\t{',
        '\t\t\t\tvalue = "";',
        f'\t\t\t\tfiles[] = {{"{PATCH}/scripts/3_Game"}};',
        '\t\t\t};',
        '\t\t\tclass worldScriptModule',
        '\t\t\t{',
        '\t\t\t\tvalue = "";',
        f'\t\t\t\tfiles[] = {{"{PATCH}/scripts/4_World"}};',
        '\t\t\t};',
        '\t\t\tclass missionScriptModule',
        '\t\t\t{',
        '\t\t\t\tvalue = "";',
        f'\t\t\t\tfiles[] = {{"{PATCH}/scripts/5_Mission"}};',
        '\t\t\t};',
        '\t\t};',
        '\t};',
        '};',
        '',
        'class CfgAmmo',
        '{',
    ]
    lines += parents_block(ammo)
    for r, o, n in ammo:
        # The whole DamageApplied class is written out, game values included, so nothing is lost
        # if the engine replaces the class instead of merging it
        override = json.loads(r['DamageOverride']) if r['DamageOverride'] else None
        lines += [
            '',
            f"\t// {r['Guns']}",
            f"\t// was Health {fmt(o['Health'])}, Shock {fmt(o['Shock'])}",
            f"\tclass {r['Class']}: {r['Parent']}",
            '\t{',
            '\t\tclass DamageApplied',
            '\t\t{',
            f"\t\t\ttype = \"{r['DamageType']}\";",
            f"\t\t\tdispersion = {fmt(r['Dispersion'])};",
        ]
        if r['BleedThreshold'] != '':
            lines.append(f"\t\t\tbleedThreshold = {fmt(r['BleedThreshold'])};")
        if override:
            lines.append('\t\t\tdefaultDamageOverride[] = {' + ', '.join('{' + ', '.join(fmt(x) for x in pair) + '}' for pair in override) + '};')
        lines += [f'\t\t\tclass {z} {{ damage = {fmt(n[z])}; }};' for z in ZONES]
        lines += ['\t\t};', '\t};']
    lines += ['};', '', 'class CfgVehicles', '{']
    lines += parents_block(armour)
    for r, o, n in armour:
        lines += [
            '',
            f"\t// share of a bullet's damage that gets through; was Health {fmt(o['Health'])}, "
            f"Blood {fmt(o['Blood'])}, Shock {fmt(o['Shock'])}",
            f"\tclass {r['Class']}: {r['Parent']}",
            '\t{',
            '\t\tclass DamageSystem',
            '\t\t{',
            '\t\t\tclass GlobalArmor',
            '\t\t\t{',
            '\t\t\t\tclass Projectile',
            '\t\t\t\t{',
        ]
        lines += [f'\t\t\t\t\tclass {z} {{ damage = {fmt(n[z])}; }};' for z in ZONES]
        lines += ['\t\t\t\t};', '\t\t\t};', '\t\t};', '\t};']
    lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()
    ammo, armour = changed_ammo(), changed_armour()
    write_config(ammo, armour, args.output)
    print(f'{len(ammo)} bullet types and {len(armour)} vests changed, written to {args.output}')


if __name__ == '__main__':
    main()
