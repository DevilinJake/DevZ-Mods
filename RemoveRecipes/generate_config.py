"""Writes src/config.cpp from recipes.csv.

Every row with Remove = Yes goes into the list the mod's script reads. Those recipes are taken
out of the right-click crafting list.

Usage:
    python generate_config.py [recipes.csv] [-o src/config.cpp]
"""
import argparse, csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_RemoveRecipes'


def read_recipes(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        rows = [r for r in csv.DictReader(f) if r['Remove'].strip().lower() in ('yes', 'y', '1', 'x')]
    for r in rows:
        if not r['Class'].strip() or any(c in r['Class'] for c in '" ,;'):
            raise SystemExit(f"Bad class name in recipes.csv: {r['Class']!r}")
    return rows


def write_config(rows, out):
    lines = [
        '// Generated by generate_config.py from recipes.csv. Edit recipes.csv and re-run it,',
        '// or edit the list below by hand: one recipe class name per line.',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {"DZ_Data", "DZ_Scripts"};',
        '\t};',
        '};',
        '',
        'class CfgMods',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        f'\t\tdir = "{PATCH}";',
        '\t\tname = "DevZ Remove Recipes";',
        '\t\tauthor = "DevilinJake";',
        '\t\ttype = "mod";',
        '\t\tdependencies[] = {"World"};',
        '',
        '\t\tclass defs',
        '\t\t{',
        '\t\t\tclass worldScriptModule',
        '\t\t\t{',
        '\t\t\t\tvalue = "";',
        f'\t\t\t\tfiles[] = {{"{PATCH}/scripts/4_World"}};',
        '\t\t\t};',
        '\t\t};',
        '\t};',
        '};',
        '',
        '// Right-click crafting recipes to remove',
        f'class Cfg{PATCH}',
        '{',
        '\trecipes[] =',
        '\t{',
    ]
    for i, r in enumerate(rows):
        comma = ',' if i < len(rows) - 1 else ''
        lines.append(f'\t\t"{r["Class"].strip()}"{comma}  // {r["Name"]} ({r["Source"]})')
    lines += ['\t};', '};']

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('recipes', nargs='?', default=os.path.join(HERE, 'recipes.csv'))
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()

    rows = read_recipes(args.recipes)
    write_config(rows, args.output)
    print(f'{len(rows)} recipes set to be removed, written to {args.output}')


if __name__ == '__main__':
    main()
