"""Writes src/config.cpp from settings.json and attacks.csv.

Each attack's new Health, Blood and Shock damage is its current value x its own multiplier in
attacks.csv, or, if that's blank, x the global one in settings.json. The same goes for clothing
wear (armorDamage).

Bleeding works differently: the game turns bleedThreshold and the Blood damage into a chance
to start bleeding (BleedChanceData.c, 'Infected' table). The Bleed multiplier scales that
chance for a player with no clothing on, and this script works out the bleedThreshold that
gives it. Clothing lowers the Blood damage, so dressed players bleed less often.

Usage:
    python generate_config.py [-o src/config.cpp]
"""
import argparse, csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = 'DevZ_InfectedDamage'
SETTINGS = {'Health': 'HealthMultiplier', 'Blood': 'BloodMultiplier', 'Shock': 'ShockMultiplier',
            'Bleed': 'BleedChanceMultiplier', 'Clothing': 'ClothingDamageMultiplier'}

# The game's bleed chance table for 'Infected' hits (3_Game\BleedChanceData.c)
INFECTED_CHANCE = {0: 0.0, 10: 5.0, 20: 15.0, 30: 27.5, 40: 40.0, 50: 55.0, 60: 60.0, 70: 70.0,
                   80: 75.0, 90: 85.0, 100: 100.0}


def bleed_chance(blood_damage, threshold):
    """Chance (0-1) that one hit starts bleeding, the way BleedChanceData.CalculateBleedChance does it."""
    armor = blood_damage / 100
    higher = max(threshold, armor) * 100
    lower = min(threshold, armor) * 100
    if lower > 100:
        return 1.0
    floor, ceil = int(lower // 10 * 10), int(-(-lower // 10) * 10)
    pos = (lower - floor) / (ceil - floor) if ceil != floor else 0
    chance_max = INFECTED_CHANCE[floor] + (INFECTED_CHANCE[ceil] - INFECTED_CHANCE[floor]) * pos
    return higher * chance_max / 10000


def threshold_for(blood_damage, chance):
    """The bleedThreshold (0-1) that gives this bleed chance; 1 if it can't go that high."""
    if bleed_chance(blood_damage, 1) <= chance:
        return 1.0
    low, high = 0.0, 1.0
    for _ in range(50):
        mid = (low + high) / 2
        low, high = (mid, high) if bleed_chance(blood_damage, mid) < chance else (low, mid)
    return round(high, 4)


def load_settings(path=os.path.join(HERE, 'settings.json')):
    with open(path, encoding='utf-8') as f:
        s = json.load(f)
    return {k: float(s.get(name, 1)) for k, name in SETTINGS.items()}


def compute(settings=None, table=os.path.join(HERE, 'attacks.csv')):
    settings = settings or load_settings()
    with open(table, newline='', encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r['mult'] = {}
        for k in SETTINGS:
            own = r[k].strip()
            r['mult'][k] = float(own) if own else settings[k]
            if r['mult'][k] < 0:
                raise SystemExit(f"{r['Class']}: {k} multiplier can't be below 0 (got {r['mult'][k]})")
        r['old'] = {k: float(r['Current' + k]) for k in ('Health', 'Blood', 'Shock', 'Clothing')}
        r['old']['Threshold'] = float(r['CurrentBleedThreshold'])
        r['new'] = {k: round(r['old'][k] * r['mult'][k], 4) for k in ('Health', 'Blood', 'Shock', 'Clothing')}
        r['old_chance'] = bleed_chance(r['old']['Blood'], r['old']['Threshold'])
        if r['mult']['Bleed'] == 1 and r['mult']['Blood'] == 1:
            r['new']['Threshold'] = r['old']['Threshold']
        else:
            r['new']['Threshold'] = threshold_for(r['new']['Blood'], min(1.0, r['old_chance'] * r['mult']['Bleed']))
        r['new_chance'] = bleed_chance(r['new']['Blood'], r['new']['Threshold'])
    return rows


def fmt(x):
    return f'{x:.4f}'.rstrip('0').rstrip('.')


def write_config(rows, out):
    changed = [r for r in rows if r['new'] != r['old']]
    addons = ['DZ_Data']
    for r in changed:
        if r['RequiredAddon'] not in addons:
            addons.append(r['RequiredAddon'])

    lines = [
        '// Generated by generate_config.py from settings.json and attacks.csv. Change those and',
        '// re-run it, or edit the numbers below by hand. A player has 100 Health, 5000 Blood and',
        '// 100 Shock. Higher bleedThreshold = more likely to start bleeding.',
        '',
        'class CfgPatches',
        '{',
        f'\tclass {PATCH}',
        '\t{',
        '\t\tunits[] = {};',
        '\t\tweapons[] = {};',
        '\t\trequiredVersion = 0.1;',
        '\t\trequiredAddons[] = {' + ', '.join(f'"{a}"' for a in addons) + '};',
        '\t};',
        '};',
        '',
        'class CfgAmmo',
        '{',
    ]
    names = {r['Class'].lower() for r in changed}
    lines += [f'\tclass {p};' for p in sorted({r['Parent'] for r in changed if r['Parent'].lower() not in names}, key=str.lower)]
    for r in changed:
        o, n = r['old'], r['new']
        lines += [
            '',
            f"\t// {r['Attacks']} ({r['Zombies']} zombie types)",
            f"\t// was Health {fmt(o['Health'])}, Blood {fmt(o['Blood'])}, Shock {fmt(o['Shock'])}, "
            f"bleed {r['old_chance']:.1%}, clothing {fmt(o['Clothing'])}",
            f"\tclass {r['Class']}: {r['Parent']}",
            '\t{',
            '\t\tclass DamageApplied',
            '\t\t{',
            f"\t\t\ttype = \"{r['DamageType']}\";",
            f"\t\t\tbleedThreshold = {fmt(n['Threshold'])};  // {r['new_chance']:.1%} bleed chance per hit, no clothing",
            f"\t\t\tclass Health {{ damage = {fmt(n['Health'])}; armorDamage = {fmt(n['Clothing'])}; }};",
            f"\t\t\tclass Blood {{ damage = {fmt(n['Blood'])}; }};",
            f"\t\t\tclass Shock {{ damage = {fmt(n['Shock'])}; }};",
            '\t\t};',
            '\t};',
        ]
    lines.append('};')

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--output', default=os.path.join(HERE, 'src', 'config.cpp'))
    args = ap.parse_args()
    changed = write_config(compute(), args.output)
    print(f'{len(changed)} attacks changed, written to {args.output}')


if __name__ == '__main__':
    main()
